reusable_bottle = int(input("How many days do you use a reusable bottle per week? "))
public_transport = int(input("How many days do you use public transport/walk per week? "))
food = int(input("How many days do you not wasted food or eat healthy food  it without any excuse? "))
workouts= int(input("How many days do you do workouts/yoga/streching per week?"))
plastic_free = int(input("How many days you declined to you plastic per week?"))
electricity_saving = int(input("How many days you sincerely for saving electricity?"))

total = (
     reusable_bottle
     + public_transport
     + food
     + workouts
     + plastic_free
     + electricity_saving
 )

maximum = 28
score = (total/maximum) * 100
print("\n" + "=" * 50)
print("Your Result")
print("=" * 50)

print("Sustainable score:", round (score,2), "%")

